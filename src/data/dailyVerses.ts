export function getTodayVersePromise(): DailyVerseItem {
  const dayOfYear = Math.floor((Date.now() - new Date(new Date().getFullYear(), 0, 0).getTime()) / 86400000);
  const index = Math.abs(dayOfYear) % DAILY_PROMISES.length;
  return DAILY_PROMISES[index];
}
